/** Which part of the night a photo belongs to; see galaChapters.ts */
export type GalaChapterKey = "auction" | "reception" | "ballroom" | "celebration";

export interface GalaPhoto {
  /** The photographer's file number, e.g. "03524" for untitled-03524.jpg */
  id: string;
  /** Full-size photo for the slideshow (1600px on the long edge) */
  src: string;
  /** 800px copy for the grid */
  thumb: string;
  /** Pixel size of the full photo; sets each tile's shape before it loads */
  width: number;
  height: number;
  chapter: GalaChapterKey;
}

const photo = (id: string, width: number, height: number, chapter: GalaChapterKey): GalaPhoto => ({
  id,
  chapter,
  src: `/gala/${id}.jpg`,
  thumb: `/gala/thumbs/${id}.jpg`,
  width,
  height,
});

/** File name a photo saves as when downloaded */
